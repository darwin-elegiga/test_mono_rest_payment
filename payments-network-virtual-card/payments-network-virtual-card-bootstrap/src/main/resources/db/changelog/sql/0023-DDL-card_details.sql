CREATE TABLE virtual_card.card_details (
    cguid UUID NOT NULL,
    card_id VARCHAR(100),
    card_holder_id VARCHAR(40),
    crn VARCHAR(20),
    card_type VARCHAR(10),
    masked_pan VARCHAR(19),
    card_status VARCHAR(10),
    status_reason JSONB,
    order_details JSONB,
    vectors _text,
    tags _text,
    tenant_attributes TEXT,
    bin_range JSONB,
    tenant_id INTEGER,
    sensitive_view JSONB,
    valid_from_mmyy VARCHAR(4),
    expiry_mmyy VARCHAR(4),
    system_attributes JSONB,
    card_lifecycle_id VARCHAR(40),
    issuance_type VARCHAR(20),
    additional_attributes TEXT,
    base_card_info JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by varchar(40),
    updated_at TIMESTAMP,
    updated_by varchar(40),
    CONSTRAINT card_details_pkey PRIMARY KEY (cguid)
);

