using VPay.Gateway.ClientProcessor.Configurations;

namespace VPay.Gateway.ClientProcessor;

[System.Diagnostics.CodeAnalysis.SuppressMessage("Design", "RCS1102:Make class static.", Justification = "This is generated by project creation and should not be changed")]
public class Program
{
    public static void Main(string[] args)
    {
        CreateHostBuilder(args).Build().Run();
    }

    public static IHostBuilder CreateHostBuilder(string[] args) =>
        Host.CreateDefaultBuilder(args)
            .BuildConfiguration()
            .UseLogging()
            .ConfigureServices(Startup.ConfigureServices);
}
