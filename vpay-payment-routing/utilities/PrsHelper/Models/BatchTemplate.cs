using System.ComponentModel;
using System.ComponentModel.DataAnnotations;
using System.Runtime.CompilerServices;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace PrsHelper.Models;
public record BatchTemplate : ITemplateFile, INotifyPropertyChanged
{
    private const string CLIENT_INFO = "Client Info";
    private const string CUSTOMIZATIONS = "Customizations";
    private string _filename = default!;
    private string _originCode = default!;
    private string _clientCode = default!;
    private string _payerAlias = default!;
    private string _payer835Id = default!;
    private string _batchNameOverride = default!;
    private string _userKeyPrefix = default!;
    private List<string> _providerTins = default!;
    private List<string> _payerSubpayerIds = default!;
    private List<string> _zipCodes = default!;

    public event PropertyChangedEventHandler? PropertyChanged;
    // This method is called by the Set accessor of each property.  
    // The CallerMemberName attribute that is applied to the optional propertyName  
    // parameter causes the property name of the caller to be substituted as an argument.  
    private void NotifyPropertyChanged([CallerMemberName] string propertyName = "")
    {
        HasChanges = true;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
    }

    [Browsable(false)]
    [JsonIgnore]
    public string Filename
    {
        get => _filename;
        set
        {
            if (value != this._filename)
            {
                _filename = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("VPay Origin Code")]
    [Description("VPay \"Origin\". Most Optum projects will use \"SEMED\".")]
    [StringLength(20, MinimumLength = 2)]
    [Display(Order = 1)]
    public string OriginCode
    {
        get => _originCode;
        set
        {
            if (value != this._originCode)
            {
                _originCode = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("VPay Client Code")]
    [Description("VPay \"TPA\". Usually 3 characters.")]
    [StringLength(10, MinimumLength = 3)]
    [Display(Order = 2)]
    public string ClientCode
    {
        get => _clientCode;
        set
        {
            if (value != this._clientCode)
            {
                _clientCode = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("Optum Payer Alias")]
    [Description("The identifier used by Optum clients to upload/download information in ECG. " +
        "Very roughly corresponds to one or more Lines of Business for the same client. " +
        "Always 5 characters.")]
    [StringLength(5, MinimumLength = 5)]
    [Display(Order = 3)]
    public string PayerAlias
    {
        get => _payerAlias;
        set
        {
            if (value != this._payerAlias)
            {
                _payerAlias = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("Optum Payer 835 Id ")]
    [Description("Optum's version of a TPA that they use internally to identify a client. Always 5 characters.")]
    [StringLength(5, MinimumLength = 5)]
    [Display(Order = 4)]
    public string Payer835Id
    {
        get => _payer835Id;
        set
        {
            if (value != this._payer835Id)
            {
                _payer835Id = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CUSTOMIZATIONS)]
    [DisplayName("Batch Name Override")]
    [Description("Custom text to insert into the batch name to easily identify it when " +
        "looking for the batch. 20 character max")]
    [StringLength(20, MinimumLength = 0)]
    public string BatchNameOverride
    {
        get => _batchNameOverride;
        set
        {
            if (value != this._batchNameOverride)
            {
                _batchNameOverride = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CUSTOMIZATIONS)]
    [DisplayName("User Key Prefix")]
    [Description("A prefix to add to each user key.  This can make them 'look' more like when they " +
        "are generated by Optum.")]
    public string UserKeyPrefix
    {
        get => _userKeyPrefix;
        set
        {
            if (value != this._userKeyPrefix)
            {
                _userKeyPrefix = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("Provider TINs")]
    [Description("Not fully sure what the Provider TINs are for.  I think it's for the bank account where the money comes from.")]
    public List<string> ProviderTins
    {
        get => _providerTins;
        set
        {
            if (value != this._providerTins)
            {
                _providerTins = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("Payer Subpayer Ids")]
    [Description("Valid PayerSubpayerIds for this client.  Make sure they are set up in " +
        "[PlatformConfig].[dbo].[PrsMapping] or the test data won't parse for dual spec properly.")]
    public List<string> PayerSubpayerIds
    {
        get => _payerSubpayerIds;
        set
        {
            if (value != this._payerSubpayerIds)
            {
                _payerSubpayerIds = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Category(CLIENT_INFO)]
    [DisplayName("Zip Codes")]
    [Description("Valid 5 digit zipcodes for this client. Not really needed... just keeps us from having to make up random ones...")]
    public List<string> ZipCodes
    {
        get => _zipCodes;
        set
        {
            if (value != this._zipCodes)
            {
                _zipCodes = value;
                NotifyPropertyChanged();
            }
        }
    }

    [Browsable(false)]
    [JsonIgnore]
    public bool HasChanges { get; set; } = false;

    public ITemplateFile Save(string fullPath)
    {
        var fileContent = JsonSerializer.Serialize(this,
           new JsonSerializerOptions { WriteIndented = true }
           );
        File.WriteAllText(fullPath, fileContent);
        this.Filename = fullPath;
        this.HasChanges = false; // We just saved any changes...
        return this;
    }

    public static BatchTemplate Load(string inputFilename)
    {
        if (!File.Exists(inputFilename))
        {
            throw new FileNotFoundException(inputFilename);
        }
        var content = File.ReadAllText(inputFilename);
        var bs = JsonSerializer.Deserialize<BatchTemplate>(content);

        if (bs is null)
        {
            throw new Exception("Batch Template had problems.");
        }
        bs.Filename = inputFilename;
        bs.HasChanges = false;
        return bs;
    }


}

